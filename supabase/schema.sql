-- Supabase / PostgreSQL Schema สำหรับระบบจองคิวร้านตัดผม
-- รองรับการใช้งานบนคลาวด์ควบคู่กับฐานข้อมูล SQLite ในเครื่อง

create type queue_source as enum ('LINE', 'WALK_IN');
create type queue_status as enum ('WAITING', 'SERVING', 'COMPLETED', 'CANCELLED');

create table if not exists public.queues (
  id bigint generated always as identity primary key,
  queue_date date not null default current_date,
  queue_number integer not null,
  display_code text not null,
  source queue_source not null,
  line_user_id text,
  customer_label text,
  status queue_status not null default 'WAITING',
  notified_near_1 boolean not null default false,
  notified_near_2 boolean not null default false,
  call_count integer not null default 0,
  last_called_at timestamptz,
  created_at timestamptz not null default now(),
  served_at timestamptz,
  closed_at timestamptz,
  constraint queues_date_number_unique unique (queue_date, queue_number)
);

-- Partial index สำหรับค้นหาคิวที่กำลังทำงานอยู่ได้อย่างรวดเร็ว
create index if not exists idx_queues_active_date_number
  on public.queues (queue_date, queue_number)
  where status in ('WAITING', 'SERVING');

-- Partial index สำหรับค้นหาคิวที่กำลังใช้งานของลูกค้า LINE
create index if not exists idx_queues_active_line_user
  on public.queues (line_user_id, queue_date)
  where status in ('WAITING', 'SERVING') and line_user_id is not null;

create table if not exists public.shop_settings (
  id integer primary key default 1 check (id = 1),
  shop_name text not null default 'ร้านตัดผม (Barber Queue)',
  notify_ahead_first integer not null default 3,
  notify_ahead_second integer not null default 1,
  repeat_call_interval_sec integer not null default 120,
  repeat_call_max_count integer not null default 3,
  walkin_popup_duration_sec integer not null default 6,
  barber_line_user_id text,
  is_shop_closed boolean not null default false,
  force_open_date text,
  last_walkin_display_code text,
  last_walkin_created_at timestamptz,
  daily_queue_limit integer default null,
  is_accepting_queue boolean not null default true,
  booking_open_time text not null default '08:30',
  booking_close_time text not null default '20:00',
  accepting_override_until timestamptz,
  line_message_templates jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  constraint shop_settings_daily_queue_limit_positive
    check (daily_queue_limit is null or daily_queue_limit between 1 and 999),
  constraint shop_settings_booking_open_time_format
    check (booking_open_time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
  constraint shop_settings_booking_close_time_format
    check (booking_close_time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
  constraint shop_settings_booking_hours_order
    check (booking_open_time <> booking_close_time)
);

insert into public.shop_settings (id)
values (1)
on conflict (id) do nothing;

create table if not exists public.notification_logs (
  id bigint generated always as identity primary key,
  queue_id bigint references public.queues(id) on delete cascade,
  display_code text not null,
  line_user_id text not null,
  trigger_type text not null, -- 'BOOKED', 'NEAR_1', 'NEAR_2', 'CALLED', 'RECALL', 'CANCELLED'
  message text not null,
  queues_ahead integer,
  delivered_via text not null default 'SIMULATOR', -- 'LINE_API' or 'SIMULATOR'
  created_at timestamptz not null default now()
);

create index if not exists idx_notification_logs_queue_id
  on public.notification_logs (queue_id);
create index if not exists idx_notification_logs_line_user_created
  on public.notification_logs (line_user_id, created_at desc);


create table if not exists public.shop_holidays (
  id bigint generated by default as identity primary key,
  holiday_date date not null,
  reason text not null default 'วันหยุดประจำร้าน',
  notified_on_day boolean not null default false,
  created_at timestamptz not null default now()
);
create unique index if not exists shop_holidays_holiday_date_key
  on public.shop_holidays (holiday_date);

create or replace function public.list_shop_holiday_dates()
returns table (holiday_date date)
language sql
stable
security definer
set search_path = ''
as $$
  select h.holiday_date
  from public.shop_holidays as h
  order by h.holiday_date;
$$;

revoke all on function public.list_shop_holiday_dates() from public;
grant execute on function public.list_shop_holiday_dates() to anon, authenticated, service_role;

-- ฟังก์ชันตรวจสอบเงื่อนไขและจองเลขคิว (Concurrency Lock)
create or replace function public.check_queue_booking_controls()
returns trigger language plpgsql as $$
declare
  limits public.shop_settings%rowtype;
  issued_count integer;
  local_time time := (now() at time zone 'Asia/Bangkok')::time;
begin
  perform pg_advisory_xact_lock(hashtext(new.queue_date::text));
  select * into limits from public.shop_settings where id = 1;
  if not limits.is_accepting_queue then
    raise exception 'QUEUE_NOT_ACCEPTING';
  end if;
  if limits.accepting_override_until is null or now() >= limits.accepting_override_until then
    if limits.booking_open_time < limits.booking_close_time then
      if local_time < limits.booking_open_time::time then
        raise exception 'BOOKING_NOT_OPEN_YET:%', limits.booking_open_time;
      end if;
      if local_time >= limits.booking_close_time::time then
        raise exception 'BOOKING_CLOSED_FOR_TODAY:%', limits.booking_close_time;
      end if;
    elsif local_time >= limits.booking_close_time::time and local_time < limits.booking_open_time::time then
      raise exception 'BOOKING_CLOSED_FOR_TODAY:%', limits.booking_close_time;
    end if;
  end if;
  if limits.daily_queue_limit is not null then
    select count(*) into issued_count from public.queues
      where queue_date = new.queue_date and status in ('WAITING', 'SERVING', 'COMPLETED');
    if issued_count >= limits.daily_queue_limit then
      raise exception 'DAILY_LIMIT_REACHED:%', limits.daily_queue_limit;
    end if;
  end if;
  select coalesce(max(queue_number), 0) + 1 into new.queue_number
    from public.queues where queue_date = new.queue_date;
  new.display_code := case when new.queue_number < 1000
    then lpad(new.queue_number::text, 3, '0') else new.queue_number::text end;
  return new;
end;
$$;

do $$ begin
  if not exists (select 1 from pg_trigger where tgname = 'queues_booking_controls' and tgrelid = 'public.queues'::regclass) then
    create trigger queues_booking_controls before insert on public.queues
      for each row execute function public.check_queue_booking_controls();
  end if;
end $$;

